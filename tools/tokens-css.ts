// npm run tokens (also run by prebuild): writes site/styles/tokens.css from src/style/tokens.ts (style SA2). The CSS is
// generated, never edited: a dark :root block, a light :root[data-theme="light"] block with the same names, derived ink
// tiers and grid alphas as colour-mixes of the theme colours, then the type families and shared sizes.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COLOR_NAMES, TOKENS, type ThemeKey } from "../src/style/tokens";

const root = fileURLToPath(new URL("..", import.meta.url));
export const TOKENS_CSS = join(root, "site/styles/tokens.css");

/** camelCase or digit-suffixed names to CSS custom property names: paperEdge -> --paper-edge, line2 -> --line-2. */
export const kebab = (name: string): string =>
  "--" + name.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();

const pct = (a: number) => `${+(a * 100).toFixed(2)}%`;
const mix = (colour: string, a: number) => `color-mix(in srgb, var(${kebab(colour)}) ${pct(a)}, transparent)`;

// Sizes are px except these: unitless counts and seconds.
const UNITLESS = new Set(["gridMajor"]);
const SECONDS = new Set(["transition"]);
const sizeValue = (key: string, v: number) => (UNITLESS.has(key) ? `${v}` : SECONDS.has(key) ? `${v}s` : `${v}px`);

function themeBlock(key: ThemeKey): string[] {
  const t = TOKENS.themes[key];
  const out = [`  color-scheme: ${key};`];
  for (const c of COLOR_NAMES) out.push(`  ${kebab(c)}: ${t[c]};`);
  out.push(`  ${kebab("patternGain")}: ${t.patternGain};`, `  ${kebab("grain")}: ${t.grain};`);
  for (const [name, a] of Object.entries(TOKENS.tiers)) out.push(`  ${kebab(name)}: ${mix("ink", a[key])};`);
  for (const [name, a] of Object.entries(TOKENS.gridTiers)) out.push(`  ${kebab(name)}: ${mix("grid", a[key])};`);
  return out;
}

export function tokensCss(): string {
  const T = TOKENS.type;
  const shared = [
    `  --font-display: ${T.display};`,
    `  --font-body: ${T.body};`,
    `  --font-mono: ${T.mono};`,
    `  --leading-body: ${T.leading};`,
    ...Object.entries(T.tracking).map(([k, v]) => `  --tracking-${kebab(k).slice(2)}: ${v}em;`),
    ...Object.entries(T.size).map(([k, v]) => `  --text-${kebab(k).slice(2)}: ${v}px;`),
    ...Object.entries(TOKENS.size).map(([k, v]) => `  --size-${kebab(k).slice(2)}: ${sizeValue(k, v)};`),
    ...Object.entries(TOKENS.ratio).map(([k, v]) => `  --ratio-${kebab(k).slice(2)}: ${v};`),
  ];
  return [
    "/* Generated by tools/tokens-css.ts from src/style/tokens.ts. Do not edit: change the tokens and rebuild. */",
    "",
    ":root {",
    ...themeBlock("dark"),
    ...shared,
    "}",
    "",
    ':root[data-theme="light"] {',
    ...themeBlock("light"),
    "}",
    "",
  ].join("\n");
}

export function writeTokensCss(path = TOKENS_CSS): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, tokensCss());
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeTokensCss();
  console.log(`wrote ${TOKENS_CSS}`);
}
